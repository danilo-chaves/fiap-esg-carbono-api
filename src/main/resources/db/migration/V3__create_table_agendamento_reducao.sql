CREATE TABLE TB_AGENDAMENTO_REDUCAO (
                                        ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        EMPRESA_ID            NUMBER        NOT NULL,
                                        TITULO                VARCHAR2(200) NOT NULL,
                                        DESCRICAO             VARCHAR2(1000),
                                        META_REDUCAO_TCO2E    NUMBER(15, 4) NOT NULL,
                                        STATUS                VARCHAR2(20)  DEFAULT 'PENDENTE' NOT NULL,
                                        DATA_INICIO           DATE          NOT NULL,
                                        DATA_FIM_PREVISTA     DATE          NOT NULL,
                                        DATA_CADASTRO         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
                                        DATA_ATUALIZACAO      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,

                                        CONSTRAINT FK_AGENDAMENTO_EMPRESA
                                            FOREIGN KEY (EMPRESA_ID) REFERENCES TB_EMPRESA(ID),

                                        CONSTRAINT CHK_STATUS_AGENDAMENTO
                                            CHECK (STATUS IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDO', 'CANCELADO'))
);