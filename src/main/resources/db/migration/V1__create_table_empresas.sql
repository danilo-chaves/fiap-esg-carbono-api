CREATE TABLE TB_EMPRESA (
                            ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            NOME             VARCHAR2(200)  NOT NULL,
                            CNPJ             VARCHAR2(18)   NOT NULL UNIQUE,
                            SETOR            VARCHAR2(100)  NOT NULL,
                            PAIS             VARCHAR2(100)  NOT NULL,
                            ATIVA            NUMBER(1)      DEFAULT 1 NOT NULL,
                            DATA_CADASTRO    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
                            DATA_ATUALIZACAO TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE  TB_EMPRESA              IS 'Empresas cadastradas no sistema ESG';
COMMENT ON COLUMN TB_EMPRESA.CNPJ         IS 'CNPJ no formato XX.XXX.XXX/XXXX-XX';
COMMENT ON COLUMN TB_EMPRESA.ATIVA        IS '1 = ativa, 0 = inativa';