CREATE TABLE TB_EMISSAO_CARBONO (
                                    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    EMPRESA_ID        NUMBER         NOT NULL,
                                    QUANTIDADE_TCO2E  NUMBER(15, 4)  NOT NULL,
                                    ESCOPO            VARCHAR2(20)   NOT NULL,
                                    DESCRICAO         VARCHAR2(500),
                                    DATA_EMISSAO      DATE           NOT NULL,
                                    DATA_REGISTRO     TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,

                                    CONSTRAINT FK_EMISSAO_EMPRESA
                                        FOREIGN KEY (EMPRESA_ID) REFERENCES TB_EMPRESA(ID),

                                    CONSTRAINT CHK_ESCOPO
                                        CHECK (ESCOPO IN ('ESCOPO_1', 'ESCOPO_2', 'ESCOPO_3'))
);

COMMENT ON COLUMN TB_EMISSAO_CARBONO.QUANTIDADE_TCO2E IS 'Toneladas de CO2 equivalente';
COMMENT ON COLUMN TB_EMISSAO_CARBONO.ESCOPO IS 'Escopo 1=diretas, 2=energia, 3=cadeia';