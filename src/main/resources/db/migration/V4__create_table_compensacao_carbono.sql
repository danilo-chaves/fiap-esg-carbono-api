CREATE TABLE TB_COMPENSACAO_CARBONO (
                                        ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        EMPRESA_ID          NUMBER        NOT NULL,
                                        TIPO                VARCHAR2(30)  NOT NULL,
                                        QUANTIDADE_TCO2E    NUMBER(15, 4) NOT NULL,
                                        DESCRICAO           VARCHAR2(500),
                                        CERTIFICADO_URL     VARCHAR2(500),
                                        DATA_COMPENSACAO    DATE          NOT NULL,
                                        DATA_REGISTRO       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,

                                        CONSTRAINT FK_COMPENSACAO_EMPRESA
                                            FOREIGN KEY (EMPRESA_ID) REFERENCES TB_EMPRESA(ID),

                                        CONSTRAINT CHK_TIPO_COMPENSACAO
                                            CHECK (TIPO IN ('CREDITO_CARBONO', 'REFLORESTAMENTO', 'ENERGIA_RENOVAVEL', 'OUTRO'))
);